# breadth-first by tree depth, but the sibling order within a depth is PhysX's
# and does not follow the URDF declaration order -- head_pitch_link sorts ahead
# of the shoulders even though the URDF declares it last. Do not hand-predict
# this list; it is dumped from the live articulation and checked by
