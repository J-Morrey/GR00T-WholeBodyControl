"""Unitree R1 (26 DOF) robot configuration for SONIC.

The R1 is a 1.2 m bipedal humanoid: 12 leg DOF, 2 waist, 10 arm and 2 head.
Compared to the G1 it has no wrist pitch/yaw (one roll DOF per wrist), no waist
pitch, and its bodies use different names -- ``pelvis_link`` rather than
``pelvis``, ``waist_yaw_link`` in place of ``torso_link``, ``*_wrist_roll_link``
in place of ``*_wrist_yaw_link``, and ``head_yaw_link`` in place of ``head_link``.
Config overrides for those names live in
``config/exp/manager/universal_token/all_modes/sonic_r1.yaml``.

Actuator gains, grouping and the standing pose come from a config that was
tested in simulation on simple R1 locomotion policies
(``holosoma/custom_assets/unitree.py::R1_CFG``), not from the G1 armature
formula used in ``g1.py``/``h2.py``.
"""

