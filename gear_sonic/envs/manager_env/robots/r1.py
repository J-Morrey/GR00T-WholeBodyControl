def _joint_of(body_name: str) -> str:
    """Return the joint driving ``body_name``.

    Every non-root R1 body owns exactly one joint and the names are regular
    (``*_link`` -> ``*_joint``); ``make_r1_sonic_mjcf.py`` asserts the one-joint
    -per-body part. G1 needs a lookup table here because ``torso_link`` is driven
    by ``waist_yaw_joint``, but R1 has no such irregularity.
    """
    return body_name.removesuffix("_link") + "_joint"


R1_MUJOCO_DOFS = [_joint_of(b) for b in R1_MUJOCO_BODIES[1:]]
R1_ISAACLAB_DOFS = [_joint_of(b) for b in R1_ISAACLAB_JOINTS[1:]]

# Index arrays: position i in the output = position mapping[i] in the input.
# Same semantics as the G1/H2 literals (verified against them):
#   MUJOCO_TO_ISAACLAB gathers a MuJoCo-ordered array into IsaacLab order.
R1_MUJOCO_TO_ISAACLAB_BODY = [R1_MUJOCO_BODIES.index(n) for n in R1_ISAACLAB_JOINTS]
R1_ISAACLAB_TO_MUJOCO_BODY = [R1_ISAACLAB_JOINTS.index(n) for n in R1_MUJOCO_BODIES]
R1_MUJOCO_TO_ISAACLAB_DOF = [R1_MUJOCO_DOFS.index(n) for n in R1_ISAACLAB_DOFS]
R1_ISAACLAB_TO_MUJOCO_DOF = [R1_ISAACLAB_DOFS.index(n) for n in R1_MUJOCO_DOFS]

R1_ISAACLAB_TO_MUJOCO_MAPPING = {
    "isaaclab_joints": R1_ISAACLAB_JOINTS,
    "isaaclab_to_mujoco_dof": R1_ISAACLAB_TO_MUJOCO_DOF,
    "mujoco_to_isaaclab_dof": R1_MUJOCO_TO_ISAACLAB_DOF,
    "isaaclab_to_mujoco_body": R1_ISAACLAB_TO_MUJOCO_BODY,
    "mujoco_to_isaaclab_body": R1_MUJOCO_TO_ISAACLAB_BODY,
}

